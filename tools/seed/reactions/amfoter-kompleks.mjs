function R(o) {
  return {
    id: null,
    category: CAT,
    title_uz: o.t,
    level: o.lvl,
    topic_uz: o.topic,
    engine: o.engine || 'rules',
    ...(o.nr ? { no_reaction: true, match: o.match } : {}),
    reactants: o.re,
    conditions: {
      heating: !!o.heat_c,
      temp_min_C: o.tmin ?? null,
      catalyst: null,
      medium: o.medium ?? null,
      light: false,
      note_uz: o.note ?? null,
    },
    equation: { molecular: o.mol ?? null, ionic_full: o.full ?? null, ionic_net: o.net ?? null, electron_balance: null },
    mechanism: { type: o.mech, steps_uz: o.steps, organic: null },
    observations: {
      precipitate: o.ppt ? ppt(o.ppt) : null,
      gas: o.gas ? gas(o.gas) : null,
      solution_color_change: o.col ? { from: o.col[0], to: o.col[1] } : null,
      heat: o.heat || 'sezilarsiz',
      flame: null,
      effects: (o.fx || []).map((type) => ({ type })),
      text_uz: o.obs,
    },
    kinetics: o.kin,
    apparatus: o.app,
    procedure_uz: o.proc,
    safety_uz: o.safe,
    explanation_uz: o.expl,
    questions_uz: o.q,
    confidence: o.conf || 'yuqori',
  };
}


const sub = (id) => { if (!S[id]) throw new Error(`modda yo'q: ${id}`); return S[id]; };
const ppt = (id) => { const s = sub(id); return { species: id, color: s.precipitate?.color || s.appearance?.color, texture: s.precipitate?.texture || 'mayda-kristall' }; };
const gas = (id) => { const s = sub(id); return { species: id, color: s.gas?.color ?? null, smell_uz: s.gas?.smell_uz ?? null }; };
const aq = (species, conc_M, volume_mL, extra = {}) => ({ species, state: 'aq', conc_M, volume_mL, ...extra });
const solid = (species, mass_g, form = 'kukun', extra = {}) => ({ species, state: 's', mass_g, form, ...extra });
const gasR = (species, extra = {}) => ({ species, state: 'g', ...extra });

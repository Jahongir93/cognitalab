// ------------------------------------------------------------------ ionic_full
function ionicFull(mol, keep = []) {
  const p = parseEquation(mol, 1);
  const side = (terms) => {
    const out = [];
    for (const t of terms) {
      const k = t.coef;
      const kk = (n) => (n === 1 ? '' : String(n));
      const raw = `${kk(k)}${t.formula}${t.annot ? `(${t.annot})` : ''}${t.mark || ''}`;
      if (t.mark || keep.includes(t.formula) || (t.annot && /kons/.test(t.annot))) { out.push(raw); continue; }
      const ent = db.resolve(t.formula);
      const s = ent && ent.kind === 'substance' ? ent.data : null;
      if (!s) { out.push(raw); continue; }
      if (s.id === 'H2SO4') { out.push(`${kk(2 * k)}H⁺`, `${kk(k)}SO4²⁻`); continue; }
      if (s.dissociation && s.solubility === 'R') {
        for (const [ion, n] of Object.entries(s.dissociation)) {
          if (ion === 'H2O') continue;
          out.push(`${kk(n * k)}${eqText(ion)}`);
        }
        continue;
      }
      out.push(raw);
    }
    return out.join(' + ');
  };
  return `${side(p.left)} = ${side(p.right)}`;
}

// ------------------------------------------------------------------ yordamchilar
const COND0 = { heating: false, temp_min_C: null, catalyst: null, medium: null, light: false, note_uz: null };

function pptObs(spec) {
  if (!spec) return null;
  const [species, texture] = Array.isArray(spec) ? spec : [spec, null];
  const s = db.substances[db.keyOf(species)];
  const color = s?.precipitate?.color || s?.appearance?.color;
  return { species, color, texture: texture || s?.precipitate?.texture || 'mayda-kristall' };
}
function gasObs(species) {
  if (!species) return null;
  const s = db.substances[db.keyOf(species)];
  const color = s?.gas?.color || (s?.state === 'g' ? s?.appearance?.color : null) || null;
  const o = { species, color };
  if (s?.gas?.smell_uz) o.smell_uz = s.gas.smell_uz;
  return o;
}

function build(def, id) {
  const eq = def.no_reaction
    ? { molecular: null, ionic_full: null, ionic_net: null, electron_balance: null }
    : {
      molecular: def.mol,
      ionic_full: def.full || ionicFull(def.mol, def.keep),
      ionic_net: def.net,
      electron_balance: def.eb,
    };
  const o = def.o || {};
  const obs = {
    precipitate: pptObs(o.ppt),
    gas: gasObs(o.gas),
    solution_color_change: o.col ? { from: o.col[0], to: o.col[1] } : null,
  };
  if (o.solid) obs.solid_color_change = { from: o.solid[0], to: o.solid[1] };
  Object.assign(obs, {
    heat: o.heat || 'sezilarsiz',
    flame: null,
    effects: (o.eff || []).map((type) => ({ type })),
    text_uz: o.txt,
  });
  const r = {
    id,
    category: CAT,
    title_uz: def.t,
    level: def.lv,
    topic_uz: def.tp,
    engine: def.eng || 'record',
  };
  if (def.no_reaction) { r.no_reaction = true; r.match = def.match; }
  Object.assign(r, {
    reactants: def.re,
    conditions: { ...COND0, ...(def.c || {}) },
    equation: eq,
    mechanism: { type: 'oksidlanish-qaytarilish', steps_uz: def.st, organic: null },
    observations: obs,
    kinetics: def.k || 'bir-zumda',
    apparatus: def.ap || ['probirka', 'tomizgich'],
    procedure_uz: def.pr,
    safety_uz: def.sf,
    explanation_uz: def.ex,
    questions_uz: def.q,
    confidence: def.cf === 'o' ? "o'rta" : 'yuqori',
  });
  return r;
}

// ------------------------------------------------------------------ yig'ish
const old = JSON.parse(readFileSync(FILE, 'utf8'));
const first = old.reactions.find((r) => r.id === 'redoks-0001');
const out = [first];
let n = 2;
for (const def of records()) {
  if (def.skip) continue;
  out.push(build(def, `redoks-${String(n).padStart(4, '0')}`));
  n++;
}

// JSON: har bir yozuv maydonlari alohida qatorda (redoks-0001 uslubida)
const lines = out.map((r) => {
  const body = Object.entries(r).map(([k, v]) => `   ${JSON.stringify(k)}: ${JSON.stringify(v).replace(/,"/g, ', "').replace(/":/g, '": ')}`).join(',\n');
  return `  {\n${body}\n  }`;
});
writeFileSync(FILE, `{\n "category": "${CAT}",\n "reactions": [\n${lines.join(',\n')}\n ]\n}\n`);
